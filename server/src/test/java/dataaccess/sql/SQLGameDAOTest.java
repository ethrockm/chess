package dataaccess.sql;

import chess.ChessGame;
import dataaccess.DataAccessException;
import dataaccess.DatabaseManager;
import dataaccess.SQLGameDAO;
import model.GameData;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.sql.SQLException;
import java.util.Collection;

import static org.junit.jupiter.api.Assertions.*;

public class SQLGameDAOTest {
    private SQLGameDAO gameDAO;

    @BeforeEach
    public void setUp() throws Exception {
        DatabaseManager.createDatabase();
        gameDAO = new SQLGameDAO();
        gameDAO.clearGames();
    }

    @Test
    public void createAndGetGamePositive() throws DataAccessException, SQLException {
        // Create a GameData object (passing 0 for the ID since MySQL will generate the real one)
        GameData newGame = new GameData(0, null, null, "My Test Game", new ChessGame());

        int gameID = gameDAO.createGame(newGame);
        assertTrue(gameID > 0, "GameID should be generated by MySQL");

        GameData retrieved = gameDAO.getGame(gameID);
        assertNotNull(retrieved);
        assertEquals("My Test Game", retrieved.gameName());
        assertNotNull(retrieved.game(), "Gson failed to deserialize the ChessGame object");
    }

    @Test
    public void getGameNegative() throws DataAccessException {
        GameData retrieved = gameDAO.getGame(9999);
        assertNull(retrieved);
    }

    @Test
    public void updateGamePositive() throws DataAccessException, SQLException {
        GameData newGame = new GameData(0, null, null, "Update Test Game", new ChessGame());
        int gameID = gameDAO.createGame(newGame);

        GameData original = gameDAO.getGame(gameID);

        // Add players and update
        GameData updated = new GameData(gameID, "Elijah", "Noah", original.gameName(), original.game());
        gameDAO.updateGame(updated);

        GameData retrieved = gameDAO.getGame(gameID);
        assertEquals("Elijah", retrieved.whiteUsername());
        assertEquals("Noah", retrieved.blackUsername());
    }

    @Test
    public void listGamesPositive() throws DataAccessException, SQLException {
        gameDAO.createGame(new GameData(0, null, null, "Game 1", new ChessGame()));
        gameDAO.createGame(new GameData(0, null, null, "Game 2", new ChessGame()));

        Collection<GameData> games = gameDAO.getGames();
        assertEquals(2, games.size());
    }
}